import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { setup, assert } from '../drawing-2026-10-20/scripts/codex-drawing-common.mjs';

const pageAudit = process.env.DRAWING_AUDIT_KIND === 'page';
const nodeKey = pageAudit ? 'pageProductionAudit' : 'retouchingAudit';
const title = pageAudit ? '页面审核' : '修图审核';
const materialLabel = pageAudit ? '页面制作图片' : '精修图片';
const firstLabel = pageAudit ? '商品主图' : '精修模特图';
const secondLabel = pageAudit ? '详情页图' : '精修动作图';
const firstField = pageAudit ? 'productMainImageUrls' : 'retouchedModelImageUrls';
const secondField = pageAudit ? 'productDetailImageUrls' : 'retouchedActionImageUrls';
const output = new URL(pageAudit ? '../page-audit-2026-10-23/' : './', import.meta.url);
await fs.mkdir(output, { recursive: true });
const ctx = await setup({ permissions: [`flycowerp:drawing:${nodeKey}`], userId: 7, roles: [] });
const { page } = ctx;
const task = { id: 88, styleNo: 'QA-RETOUCH', procInstId: 'qa-retouch', currentNodeKey: nodeKey, currentNodeTaskId: '9007199254740993123', currentNodeAssigneeId: '7', currentNodeStatus: 2, flowStatus: 2 };
const image = name => ({ originalUrl: `https://example.test/${name}.png`, previewUrl: `https://example.test/p-${name}.png`, thumbnailUrl: `https://example.test/t-${name}.png` });
const styles = [0, 1].map(i => ({ id: `900719925474099310${i}`, styleNo: `QA-RETOUCH-${i}`, styleName: `款式${i}`, clothingProductUrl: image(`clothing-${i}`), aiModelImageUrls: [image('not-retouched')], ...(pageAudit ? { retouchedModelImageUrls: [image('not-page')] } : {}), [firstField]: i ? [] : JSON.stringify(pageAudit ? [image('model'), ...[2, 3, 4, 5].map(index => image(`main-${index}`))] : [image('model')]), [secondField]: i ? [image('action-1')] : [image('action')] }));
const calls = [];
let failMaterials = false;
let missingFields = false;
let failAudit = false;
let holdAudit = false;
let release;
await page.route('**/admin-api/flycowerp/**', async route => {
  const request = route.request();
  const url = new URL(request.url());
  const endpoint = url.pathname.split('/flycowerp/')[1];
  const body = request.headers()['content-type']?.includes('application/json') ? request.postDataJSON() : null;
  calls.push({ endpoint, body });
  let data;
  if (endpoint === 'newProductTask/page') data = { list: [task], total: 1 };
  else if (endpoint === 'newProductStyle/list') {
    if (failMaterials) return route.fulfill({ json: { code: 500, msg: '模拟材料加载失败' } });
    data = missingFields ? styles.map(style => { const rest = { ...style }; delete rest[firstField]; delete rest[secondField]; return rest; }) : styles;
  } else if (endpoint === 'flow/audit') {
    if (holdAudit) await new Promise(resolve => { release = resolve; });
    data = !failAudit;
  } else throw Error(`Unexpected API: ${endpoint}`);
  await route.fulfill({ json: { code: 0, data } });
});
const count = endpoint => calls.filter(call => call.endpoint === endpoint).length;
const dialog = () => page.getByRole('dialog').last();
const opinion = () => dialog().getByRole('textbox', { name: '审核意见' });
async function open() {
  await ctx.click('审核', ctx.row(task.styleNo));
  await dialog().getByText(firstLabel, { exact: true }).waitFor();
}
try {
  await ctx.navigate(`/drawing/${nodeKey}`);
  await open();
  assert.equal(new URL(page.url()).search, '');
  assert.equal(count('newProductTask/get/88'), 0);
  assert.equal(count('flow/draft/get'), 0);
  const model = dialog().locator(`.ant-collapse-item-active [data-audit-image-group="${firstLabel}"]`);
  const action = dialog().locator(`.ant-collapse-item-active [data-audit-image-group="${secondLabel}"]`);
  assert.equal(await model.locator('img').first().getAttribute('src'), image('model').previewUrl);
  assert.equal(await action.locator('img').getAttribute('src'), image('action').previewUrl);
  assert.equal(await dialog().locator('img[src*="not-retouched"]').count(), 0);
  assert.equal(await dialog().locator('img[src*="not-page"]').count(), 0);
  if (pageAudit) {
    assert.equal(await model.locator('img').count(), 5);
    assert.deepEqual(await model.locator('span.text-center').allTextContents(), ['主图1', '主图2', '面料3', '主图4', '搭配5']);
  }
  await ctx.click('通过', dialog());
  await dialog().getByText('请填写审核意见', { exact: true }).waitFor();
  assert.equal(count('flow/audit'), 0);
  await model.locator('.ant-image').first().click();
  await page.locator('.ant-image-preview-img').waitFor();
  assert.equal(await page.locator('.ant-image-preview-img').getAttribute('src'), image('model').originalUrl);
  await page.locator('.ant-image-preview-operations .anticon-close').click();
  await page.locator('.ant-image-preview-img').waitFor({ state: 'hidden' });
  await dialog().getByText('第2款 · QA-RETOUCH-1 · 款式1', { exact: true }).click();
  await dialog().getByText(`未提交此类${materialLabel}`, { exact: true }).waitFor();
  assert.equal(await action.locator('img').getAttribute('src'), image('action-1').previewUrl);
  await dialog().getByText('第1款 · QA-RETOUCH-0 · 款式0', { exact: true }).click();
  await opinion().fill('  精修审核意见  ');
  failAudit = true;
  await ctx.click('通过', dialog());
  await page.getByText('审核未成功，请重试', { exact: true }).waitFor();
  assert.equal(await opinion().inputValue(), '  精修审核意见  ');
  failAudit = false;
  const previousId = task.currentNodeTaskId;
  task.currentNodeTaskId = 'changed';
  await ctx.click('通过', dialog());
  await dialog().getByText('任务状态或节点已变化，请关闭窗口并刷新列表后重试', { exact: true }).waitFor();
  assert.equal(count('flow/audit'), 1);
  task.currentNodeTaskId = previousId;
  await ctx.click('刷新材料', dialog());
  await model.locator('img').first().waitFor();
  holdAudit = true;
  const requested = page.waitForRequest(request => request.url().endsWith('/flow/audit'));
  await ctx.click('驳回', dialog());
  await requested;
  assert.equal(await dialog().getByRole('button', { name: '取消', exact: true }).isDisabled(), true);
  await page.evaluate(async () => document.querySelector('#app').__vue_app__.config.globalProperties.$router.push('/generation/image'));
  assert.equal(new URL(page.url()).pathname, `/drawing/${nodeKey}`);
  const payload = calls.findLast(call => call.endpoint === 'flow/audit').body;
  assert.equal(payload.nodeKey, nodeKey);
  assert.equal(payload.nodeTaskId, previousId);
  assert.equal(payload.procInstId, task.procInstId);
  assert.equal(payload.auditInfoVO.auditStatus, 2);
  assert.equal(payload.auditInfoVO.contentText, '精修审核意见');
  release(); release = undefined; holdAudit = false;
  await dialog().waitFor({ state: 'hidden' });
  await open();
  await opinion().fill('通过审核');
  await ctx.click('通过', dialog());
  await page.getByText(`${title}已通过`, { exact: true }).waitFor();
  await dialog().waitFor({ state: 'hidden' });
  missingFields = true;
  await open();
  await dialog().getByText('暂未获取到上一步提交的图片，请刷新后重试', { exact: true }).first().waitFor();
  assert.equal(await dialog().locator('[data-retouch-materials] img').count(), 0);
  assert.equal(await dialog().getByRole('button', { name: '通过', exact: true }).isEnabled(), true);
  await ctx.click('通过', dialog());
  await page.getByText(`暂未获取到上一步提交的${materialLabel}，请刷新后重试`, { exact: true }).waitFor();
  missingFields = false;
  failMaterials = true;
  await ctx.click('刷新材料', dialog());
  await dialog().locator('.ant-alert-error').waitFor();
  failMaterials = false;
  await ctx.click('重试', dialog());
  await model.locator('img').first().waitFor();
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.locator('.ant-message-notice').last().waitFor({ state: 'hidden' });
  await page.screenshot({ path: fileURLToPath(new URL('audit.png', output)) });
  const bounds = await dialog().boundingBox();
  assert.ok(bounds.y + bounds.height <= 768);
  await ctx.click('取消', dialog());
  await ctx.finish();
  await fs.writeFile(new URL('result.json', output), JSON.stringify({ mode: 'mock-browser', nodeKey, verified: ['direct modal without navigation', 'submitted materials only, original preview and per-style isolation', 'five main image positions in page audit', 'required opinion, pass/reject context, failure retains inputs', 'changed node blocks writes; pending blocks close/navigation', 'missing fields and failed loading retry', '1366x768 modal bounds'], runtimeErrors: ctx.state.errors, calls }, null, 2));
  console.log(`PASS ${title}: submitted materials, previews, validation, scope, pass/reject, retry and layout`);
} catch (error) {
  release?.();
  console.error('Errors:', ctx.state.errors);
  await ctx.browser.close();
  throw error;
}
